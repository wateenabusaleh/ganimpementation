#Implementing the Vanilla GAN
import torch
import torch.nn as nn
import torch.optim as optim
import pandas as pd
import numpy as np

# 1. Load Data
data = pd.read_csv('X_fraud.csv')
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# Convert to PyTorch Tensor
real_data = torch.tensor(data.values, dtype=torch.float32).to(device)
data_dim = real_data.shape[1] # Number of columns (features)

# 2. Define Hyperparameters
NOISE_DIM = 16
LR = 0.001
EPOCHS = 2000  # High number because dataset is tiny (492 rows)
BATCH_SIZE = 64

# 3. Define Vanilla GAN Architecture

# Generator: Takes Noise -> Outputs Fake Data
class Generator(nn.Module):
    def __init__(self):
        super(Generator, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(NOISE_DIM, 32),
            nn.ReLU(),
            nn.Linear(32, 64),
            nn.ReLU(),
            nn.Linear(64, data_dim),
            # No Tanh/Sigmoid at end because we standardized data (can be -ve or +ve)
        )

    def forward(self, x):
        return self.net(x)

# Discriminator: Takes Data -> Outputs Probability (Real vs Fake)
class Discriminator(nn.Module):
    def __init__(self):
        super(Discriminator, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(data_dim, 64),
            nn.LeakyReLU(0.2),
            nn.Linear(64, 32),
            nn.LeakyReLU(0.2),
            nn.Linear(32, 1),
            nn.Sigmoid() # Probability output (0 to 1)
        )

    def forward(self, x):
        return self.net(x)

# Initialize
gen = Generator().to(device)
disc = Discriminator().to(device)

opt_gen = optim.Adam(gen.parameters(), lr=LR)
opt_disc = optim.Adam(disc.parameters(), lr=LR)

criterion = nn.BCELoss() # Binary Cross Entropy Loss

# 4. Training Loop
print("Starting Vanilla GAN Training...")

dataset = torch.utils.data.TensorDataset(real_data)
loader = torch.utils.data.DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

for epoch in range(EPOCHS):
    for batch_idx, (real,) in enumerate(loader):
        batch_size = real.shape[0]

        ### Train Discriminator: max log(D(x)) + log(1 - D(G(z)))
        noise = torch.randn(batch_size, NOISE_DIM).to(device)
        fake = gen(noise)

        disc_real = disc(real).view(-1)
        loss_disc_real = criterion(disc_real, torch.ones_like(disc_real))

        disc_fake = disc(fake.detach()).view(-1)
        loss_disc_fake = criterion(disc_fake, torch.zeros_like(disc_fake))

        loss_disc = (loss_disc_real + loss_disc_fake) / 2
        disc.zero_grad()
        loss_disc.backward()
        opt_disc.step()

        ### Train Generator: min log(1 - D(G(z))) <-> max log(D(G(z)))
        output = disc(fake).view(-1)
        loss_gen = criterion(output, torch.ones_like(output))

        gen.zero_grad()
        loss_gen.backward()
        opt_gen.step()

    if epoch % 500 == 0:
        print(f"Epoch [{epoch}/{EPOCHS}] Loss D: {loss_disc:.4f}, loss G: {loss_gen:.4f}")

# 5. Generate Synthetic Data for Balancing
# We want to generate enough fraud cases to match the majority class roughly
# or at least a significant amount (e.g., 20,000 samples)
num_synthetic = 20000
with torch.no_grad():
    noise = torch.randn(num_synthetic, NOISE_DIM).to(device)
    fake_data = gen(noise).cpu().numpy()

# Save to CSV
df_fake = pd.DataFrame(fake_data, columns=data.columns)
df_fake['Class'] = 1 # Label them as Fraud
df_fake.to_csv('vanilla_gan_fraud.csv', index=False)
print("Finished. Synthetic data saved to 'vanilla_gan_fraud.csv'.")

#Implement WGAN
import torch
import torch.nn as nn
import torch.optim as optim
import pandas as pd
import numpy as np

# 1. Load Data
data = pd.read_csv('X_fraud.csv')
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

real_data = torch.tensor(data.values, dtype=torch.float32).to(device)
data_dim = real_data.shape[1]

# 2. Hyperparameters
NOISE_DIM = 16
LR = 0.00005        # WGAN needs lower learning rate
EPOCHS = 2000
BATCH_SIZE = 64
CLIP_VALUE = 0.01   # WGAN Weight clipping
N_CRITIC = 5        # Train critic 5 times for every 1 gen step

# 3. WGAN Architecture

class Generator(nn.Module):
    def __init__(self):
        super(Generator, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(NOISE_DIM, 32),
            nn.ReLU(),
            nn.Linear(32, 64),
            nn.ReLU(),
            nn.Linear(64, data_dim),
        )

    def forward(self, x):
        return self.net(x)

class Critic(nn.Module):
    def __init__(self):
        super(Critic, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(data_dim, 64),
            nn.LeakyReLU(0.2),
            nn.Linear(64, 32),
            nn.LeakyReLU(0.2),
            nn.Linear(32, 1)
            # NO Sigmoid here! WGAN output is unbound.
        )

    def forward(self, x):
        return self.net(x)

# Initialize
gen = Generator().to(device)
critic = Critic().to(device)

# WGAN uses RMSprop usually (Adam can cause instability in WGAN)
opt_gen = optim.RMSprop(gen.parameters(), lr=LR)
opt_critic = optim.RMSprop(critic.parameters(), lr=LR)

# 4. Training Loop
print("Starting WGAN Training...")

dataset = torch.utils.data.TensorDataset(real_data)
loader = torch.utils.data.DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

for epoch in range(EPOCHS):
    for batch_idx, (real,) in enumerate(loader):
        batch_size = real.shape[0]
        real = real.to(device)

        # --- Train Critic ---
        # We train the critic more often than the generator
        for _ in range(N_CRITIC):
            noise = torch.randn(batch_size, NOISE_DIM).to(device)
            fake = gen(noise)

            critic_real = critic(real).reshape(-1)
            critic_fake = critic(fake).reshape(-1)

            # WGAN Loss: -(mean(real) - mean(fake))
            # We want to maximize the gap between real and fake scores
            loss_critic = -(torch.mean(critic_real) - torch.mean(critic_fake))

            critic.zero_grad()
            loss_critic.backward(retain_graph=True)
            opt_critic.step()

            # Clip weights to enforce 1-Lipschitz constraint
            for p in critic.parameters():
                p.data.clamp_(-CLIP_VALUE, CLIP_VALUE)

        # --- Train Generator ---
        # Train Generator only once after N_CRITIC steps
        noise = torch.randn(batch_size, NOISE_DIM).to(device)
        fake = gen(noise)
        critic_fake = critic(fake).reshape(-1)

        # Generator wants to maximize Critic's score for fakes
        loss_gen = -torch.mean(critic_fake)

        gen.zero_grad()
        loss_gen.backward()
        opt_gen.step()

    if epoch % 500 == 0:
        print(f"Epoch [{epoch}/{EPOCHS}] Loss Critic: {loss_critic.item():.4f}, Loss Gen: {loss_gen.item():.4f}")

# 5. Generate Synthetic Data
num_synthetic = 20000
with torch.no_grad():
    noise = torch.randn(num_synthetic, NOISE_DIM).to(device)
    fake_data = gen(noise).cpu().numpy()

# Save
df_fake = pd.DataFrame(fake_data, columns=data.columns)
df_fake['Class'] = 1
df_fake.to_csv('wgan_fraud.csv', index=False)
print("Finished. Synthetic data saved to 'wgan_fraud.csv'.")

import torch
