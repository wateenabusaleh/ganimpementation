# 2. Hyperparameters
NOISE_DIM = 16
LR = 0.0002
EPOCHS = 2000
BATCH_SIZE = 64

# 3. LSGAN Architecture
class LSGAN_Generator(nn.Module):
    def __init__(self):
        super(LSGAN_Generator, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(NOISE_DIM, 32),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.Linear(32, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Linear(64, data_dim),
        )

    def forward(self, x):
        return self.net(x)

class LSGAN_Discriminator(nn.Module):
    def __init__(self):
        super(LSGAN_Discriminator, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(data_dim, 64),
            nn.LeakyReLU(0.2),
            nn.Linear(64, 32),
            nn.LeakyReLU(0.2),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        return self.net(x)

# Initialize models
ls_gen = LSGAN_Generator().to(device)
ls_disc = LSGAN_Discriminator().to(device)

# Optimizers
opt_gen = optim.Adam(ls_gen.parameters(), lr=LR, betas=(0.5, 0.999))
opt_disc = optim.Adam(ls_disc.parameters(), lr=LR, betas=(0.5, 0.999))

# Loss Function
criterion = nn.MSELoss()

# 4. Training Loop
print("Starting LSGAN Training...")

dataset = torch.utils.data.TensorDataset(real_data)
loader = torch.utils.data.DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

for epoch in range(EPOCHS):
    for batch_idx, (real,) in enumerate(loader):
        batch_size = real.shape[0]
        real = real.to(device)

        # Train Discriminator
        noise = torch.randn(batch_size, NOISE_DIM).to(device)
        fake = ls_gen(noise)

        disc_real = ls_disc(real).view(-1)
        loss_d_real = criterion(disc_real, torch.ones_like(disc_real))

        disc_fake = ls_disc(fake.detach()).view(-1)
        loss_d_fake = criterion(disc_fake, torch.zeros_like(disc_fake))

        loss_disc = 0.5 * (loss_d_real + loss_d_fake)

        ls_disc.zero_grad()
        loss_disc.backward()
        opt_disc.step()

        # Train Generator
        output = ls_disc(fake).view(-1)
        loss_gen = criterion(output, torch.ones_like(output))

        ls_gen.zero_grad()
        loss_gen.backward()
        opt_gen.step()

    if epoch % 500 == 0:
        print(f"Epoch [{epoch}/{EPOCHS}] Loss D: {loss_disc.item():.4f}, Loss G: {loss_gen.item():.4f}")

# 5. Generate and Save Data
num_synthetic = 20000
with torch.no_grad():
    noise = torch.randn(num_synthetic, NOISE_DIM).to(device)
    ls_fake_data = ls_gen(noise).cpu().numpy()

